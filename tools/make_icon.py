#!/usr/bin/env python3
"""Generate the application icon (a golden ankh) from the pixel art below.

Writes, relative to the repository root:
  icon.png                     256x256 preview / source image
  u5win/u5win.ico              Windows program icon (16, 32, 48, 256 px)
  src/graphics/app_icon.h      64x64 RGBA pixels the game sets as its window icon

Usage: tools/make_icon.py   (requires Pillow)
"""

import os

from PIL import Image

# 32x32 pixel art: '#' outline, 'H' highlight, 'G' gold, 'S' shadow, '.' clear.
ART = [
    "................................",
    "...........########.............",
    ".........###HHHHGG###...........",
    "........##HHGGGGGGGS##..........",
    ".......##HGG######GGS##.........",
    ".......#HG##......##GS#.........",
    "......##HG#........#GS##........",
    "......#HG##........##GS#........",
    "......#HG#..........#GS#........",
    "......#HG#..........#GS#........",
    "......#HG##........##GS#........",
    "......##HG#........#GS##........",
    ".......#HGG##....##GGS#.........",
    ".......##HGG#....#GGS##.........",
    "..#######HHG#....#GGS#######....",
    "..#HHHHHHHHGG####GGSSSSSSSS#....",
    "..#HGGGGGGGGGGGGGGGGGGGGGGS#....",
    "..#GSSSSSSSSGGGGGGSSSSSSSSS#....",
    "..##########HGGGGS##########....",
    "...........#HGGGGS#.............",
    "...........#HGGGGS#.............",
    "...........#HGGGGS#.............",
    "...........#HGGGGS#.............",
    "...........#HGGGGS#.............",
    "...........#HGGGGS#.............",
    "...........#HGGGGS#.............",
    "...........#HGGGGS#.............",
    "..........##HGGGGS##............",
    "..........#HGGGGGGS#............",
    "..........##########............",
    "................................",
    "................................",
]

COLORS = {
    '#': (40, 20, 8, 255),
    'H': (255, 240, 150, 255),
    'G': (232, 180, 40, 255),
    'S': (160, 100, 20, 255),
    '.': (0, 0, 0, 0),
}


def draw():
    art = Image.new('RGBA', (32, 32))
    for y, row in enumerate(ART):
        assert len(row) == 32, f"row {y} is {len(row)} wide"
        for x, ch in enumerate(row):
            art.putpixel((x, y), COLORS[ch])

    # Center the drawing in the square.
    box = art.getbbox()
    w, h = box[2] - box[0], box[3] - box[1]
    centered = Image.new('RGBA', (32, 32))
    centered.paste(art.crop(box), ((32 - w) // 2, (32 - h) // 2))
    return centered


def scaled(img, size):
    # Whole-number scaling keeps the pixels crisp; 16 px needs real resampling.
    return img.resize((size, size), Image.NEAREST if size % 32 == 0 else Image.LANCZOS)


def write_header(img, path):
    data = img.tobytes()  # RGBA, row by row
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    with open(path, 'w') as f:
        f.write("/* Generated by tools/make_icon.py - do not edit by hand. */\n")
        f.write("#ifndef _GRAPHICS_APP_ICON_H\n#define _GRAPHICS_APP_ICON_H\n\n")
        f.write(f"#define APP_ICON_SIZE {img.width}\n\n")
        f.write("/* RGBA, APP_ICON_SIZE x APP_ICON_SIZE */\n")
        f.write("static const unsigned char g_appIcon[] =\n{\n" + "\n".join(lines) + "\n};\n\n#endif\n")


def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
    icon = draw()

    scaled(icon, 256).save(os.path.join(root, 'icon.png'))
    scaled(icon, 256).save(os.path.join(root, 'u5win', 'u5win.ico'),
                           sizes=[(16, 16), (32, 32), (48, 48), (256, 256)])
    write_header(scaled(icon, 64), os.path.join(root, 'src', 'graphics', 'app_icon.h'))
    print("Wrote icon.png, u5win/u5win.ico and src/graphics/app_icon.h")


if __name__ == '__main__':
    main()
